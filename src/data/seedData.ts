const HOUR = 3600 * 1000;
const DAY = 24 * HOUR;

function isoOffset(msOffset: number): string {
  return new Date(Date.now() + msOffset).toISOString();
}

function localDateString(msOffset = 0): string {
  const d = new Date(Date.now() + msOffset);
  const year = d.getFullYear();
  const month = String(d.getMonth() + 1).padStart(2, '0');
  const day = String(d.getDate()).padStart(2, '0');
  return `${year}-${month}-${day}`;
}

function localTimeString(msOffset = 0): string {
  const d = new Date(Date.now() + msOffset);
  const hh = String(d.getHours()).padStart(2, '0');
  const mm = String(d.getMinutes()).padStart(2, '0');
  return `${hh}:${mm}`;
}

